// Generates lib/tokens.generated.ts from the web's src/styles/theme.css (:root and its dark
// block), so web and native read the same Studio tokens and can't drift (native-app-plan §2).
// Run: npm run tokens. `npm run check:tokens` fails if the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const css = readFileSync(path.resolve(here, '../../../src/styles/theme.css'), 'utf8')
const out = path.resolve(here, '../lib/tokens.generated.ts')

const block = (src) => {
  const vars = {}
  for (const m of src.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/gi)) vars[m[1]] = m[2].trim()
  return vars
}
const rootStart = css.indexOf(':root {')
const root = block(css.slice(rootStart, css.indexOf('\n}', rootStart)))
const darkAt = css.indexOf('@media (prefers-color-scheme: dark)')
const darkRoot = css.indexOf(':root {', darkAt)
const dark = { ...root, ...block(css.slice(darkRoot, css.indexOf('}', darkRoot))) }

const resolve = (vars) => {
  const res = {}
  const get = (k, seen = new Set()) => {
    const v = vars[k]
    if (v == null) return undefined
    const ref = /^var\(--([a-z0-9-]+)\)$/i.exec(v)
    if (!ref) return v
    if (seen.has(k)) throw new Error('token cycle at --' + k)
    seen.add(k)
    return get(ref[1], seen)
  }
  for (const k of Object.keys(vars)) {
    if (k.startsWith('font-') || k === 'shadow') continue
    const v = get(k)
    if (v != null) res[k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())] = v.endsWith('px') ? parseFloat(v) : v
  }
  return res
}

const light = resolve(root), darkT = resolve(dark)
const body = `// GENERATED by scripts/tokens.mjs from src/styles/theme.css. Do not edit; run \`npm run tokens\`.
export const light = ${JSON.stringify(light, null, 2)}

export type Tokens = typeof light

export const dark: Tokens = ${JSON.stringify(darkT, null, 2)}
`
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== body) { console.error('lib/tokens.generated.ts is out of date: run npm run tokens'); process.exit(1) }
  console.log('tokens up to date')
} else {
  writeFileSync(out, body)
  console.log('wrote', path.relative(process.cwd(), out), Object.keys(light).length, 'tokens')
}
